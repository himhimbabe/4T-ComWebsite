import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { solutions } from "./solution-content.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const languages = [
  { id: "en", lang: "en-HK", label: "EN", name: "English" },
  { id: "zh-hant", lang: "zh-Hant-HK", label: "繁中", name: "繁體中文" },
  { id: "zh-hans", lang: "zh-Hans", label: "简中", name: "简体中文" },
];
const menuLanguages = [languages[1], languages[0], languages[2]];
const labels = {
  skip: ["Skip to content", "跳至主要內容", "跳至主要内容"],
  menu: ["Main menu", "主選單", "主菜单"],
  navigation: ["Main navigation", "主要導覽", "主导航"],
  language: ["Language", "選擇語言", "选择语言"],
  hardware: ["4S hardware", "4S 安全硬件", "4S 安全硬件"],
  positioning: ["Positioning", "定位系統", "定位系统"],
  services: ["AI & software", "AI 與軟件", "AI 与软件"],
  projects: ["Customers", "客戶", "客户"],
  about: ["About", "關於我們", "关于我们"],
  contact: ["Contact us", "聯絡我們", "联系我们"],
  features: ["How it works", "運作方式", "工作原理"],
  specs: ["Configuration and specifications", "配置及規格", "配置及规格"],
  enquire: ["Discuss your project", "查詢項目方案", "咨询项目方案"],
  email: ["Email ForThink", "電郵 ForThink", "邮件联系 ForThink"],
  whatsapp: ["Chat on WhatsApp", "使用 WhatsApp 聯絡", "通过 WhatsApp 联系"],
  related: ["Explore related solutions", "了解相關方案", "了解相关方案"],
  home: ["ForThink home", "ForThink 首頁", "ForThink 首页"],
  company: ["ForThink (HK) Technology Co., Limited", "四相致新（香港）科技有限公司", "四相致新（香港）科技有限公司"],
};
const email = "sales@forthink.com.hk";
const whatsapp = "https://wa.me/85265855766";
const byId = new Map(solutions.map(solution => [solution.id, solution]));

function escapeHtml(value) {
  return value.replace(/[&<>"']/g, character => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[character]);
}

function pathFor(solution, language) {
  const folder = language.id === "en" ? "solutions" : "solutions/" + language.id;
  return folder + "/" + solution.id + ".html";
}

function renderPage(solution, language, index) {
  const local = value => escapeHtml(value[index]);
  const label = key => local(labels[key]);
  const title = local(solution.title);
  const intro = local(solution.intro);
  const base = language.id === "en" ? "../" : "../../";
  const home = language.id === "zh-hant" ? base : base + "?lang=" + language.id;
  const asset = name => base + "assets/" + name;
  const pageTitle = title + " | ForThink Hong Kong";
  const languageLinks = menuLanguages.map(option => {
    const current = option.id === language.id ? ' aria-current="true"' : "";
    return '            <li><a href="' + base + pathFor(solution, option) + '" lang="' + option.lang +
      '" hreflang="' + option.lang + '" data-language="' + option.id + '"' + current + '>' + option.name + "</a></li>";
  }).join("\n");
  const alternateLinks = languages.map(option =>
    '  <link rel="alternate" hreflang="' + option.lang + '" href="' + base + pathFor(solution, option) + '">'
  ).join("\n");
  const navLinks = ["hardware", "positioning", "services", "projects", "about"].map(key => {
    const className = key === "services" ? ' class="nav-services"' : "";
    return '        <a' + className + ' href="' + home + "#" + key + '">' + label(key) + "</a>";
  }).join("\n");
  const features = solution.features.map(([name, description]) =>
    '          <div class="solution-feature" data-scroll-reveal><h3>' + local(name) + "</h3><p>" + local(description) + "</p></div>"
  ).join("\n");
  const specs = solution.specs.map(([name, value]) =>
    "            <div><dt>" + local(name) + "</dt><dd>" + local(value) + "</dd></div>"
  ).join("\n");
  const media = solution.media ? [
    '        <figure class="solution-media" data-scroll-reveal>',
    '          <img src="' + asset(solution.media.image) + '" alt="' + local(solution.media.caption) + '" loading="lazy">',
    '          <figcaption>' + local(solution.media.caption) + "</figcaption>",
    "        </figure>",
  ].join("\n") : "";
  const source = solution.source ?
    '          <a class="text-link" href="' + solution.source[0] + '"><span>' + local(solution.source[1]) + '</span><span aria-hidden="true">↗</span></a>' : "";
  const related = solution.related.map(id => {
    const item = byId.get(id);
    return '          <li><a href="' + base + pathFor(item, language) + '"><span>' + local(item.title) + '</span><span aria-hidden="true">→</span></a></li>';
  }).join("\n");
  const subject = encodeURIComponent(solution.title[index] + " — ForThink");
  const imageClass = solution.imageStyle === "device" ? " solution-hero-device" : "";

  return `<!doctype html>
<!-- Generated by node scripts/build-solutions.mjs. Edit scripts/solution-content.mjs for page copy. -->
<html lang="${language.lang}" data-locale="${language.id}" data-type="product">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${pageTitle}</title>
  <meta name="description" content="${intro}">
  <meta name="theme-color" content="#101d2a">
  <meta property="og:type" content="website">
  <meta property="og:title" content="${pageTitle}">
  <meta property="og:description" content="${intro}">
  <meta property="og:image" content="https://www.forthink.com.hk/assets/${solution.image}">
${alternateLinks}
  <link rel="icon" href="${asset("favicon.png")}">
  <link rel="stylesheet" href="${base}styles.css">
  <link rel="stylesheet" href="${base}solution.css">
  <script src="${base}site.js" defer></script>
  <script src="${base}scroll-motion.js" defer></script>
</head>
<body id="top" class="solution-page">
  <a class="skip" href="#main">${label("skip")}</a>
  <header class="header">
    <div class="wrap header-inner">
      <a href="${home}" class="brand" aria-label="ForThink">
        <img src="${asset("forthink.webp")}" width="560" height="167" alt="ForThink 四相科技">
      </a>
      <button class="menu-toggle" type="button" aria-label="${label("menu")}" aria-expanded="false" aria-controls="navigation" hidden>
        <span class="menu-icon" aria-hidden="true"></span>
      </button>
      <nav id="navigation" class="navigation" aria-label="${label("navigation")}">
${navLinks}
        <a href="#contact" class="nav-contact">${label("contact")}</a>
      </nav>
      <div class="header-actions">
        <details class="language-menu" hidden>
          <summary aria-label="${label("language")}"><span data-active-language>${language.label}</span></summary>
          <ul>
${languageLinks}
          </ul>
        </details>
        <a class="button primary header-contact" href="#contact">${label("contact")}</a>
      </div>
    </div>
  </header>
  <main id="main" tabindex="-1">
    <section class="solution-hero" aria-labelledby="solution-title">
      <div class="wrap">
        <a class="solution-back" href="${home}#${solution.section}"><span aria-hidden="true">←</span> ${label(solution.section)}</a>
        <div class="solution-hero-grid">
          <div data-enter>
            <h1 id="solution-title">${title}</h1>
            <p>${intro}</p>
            <a class="button primary" href="#contact"><span>${label("enquire")}</span><span aria-hidden="true">↘</span></a>
          </div>
          <div class="solution-hero-visual${imageClass}">
            <img src="${asset(solution.image)}" alt="${local(solution.imageAlt)}" fetchpriority="high">
          </div>
        </div>
      </div>
    </section>
    <section class="section wrap solution-body" id="capabilities" aria-labelledby="capabilities-title">
      <div class="solution-split">
        <h2 id="capabilities-title" data-scroll-reveal>${solution.featuresLabel ? local(solution.featuresLabel) : label("features")}</h2>
        <div class="solution-feature-list">
${features}
        </div>
      </div>
${media}
    </section>
    <section class="section solution-specs" id="details" aria-labelledby="details-title">
      <div class="wrap solution-split">
        <h2 id="details-title" data-scroll-reveal>${solution.specsLabel ? local(solution.specsLabel) : label("specs")}</h2>
        <div data-scroll-reveal>
          <dl class="solution-facts">
${specs}
          </dl>
${source}
        </div>
      </div>
    </section>
    <section class="contact solution-contact" id="contact" aria-labelledby="contact-title">
      <div class="wrap solution-split">
        <h2 id="contact-title">${label("enquire")}</h2>
        <div>
          <p>${local(solution.fit)}</p>
          <div class="solution-actions">
            <a class="button primary" href="mailto:${email}?subject=${subject}"><span>${label("email")}</span><span aria-hidden="true">↗</span></a>
            <a class="hero-link" href="${whatsapp}">${label("whatsapp")} <span aria-hidden="true">↗</span></a>
          </div>
        </div>
      </div>
    </section>
    <section class="section wrap solution-related" aria-labelledby="related-title">
      <h2 id="related-title" data-scroll-reveal>${label("related")}</h2>
      <ul>
${related}
      </ul>
    </section>
  </main>
  <footer class="solution-footer">
    <div class="wrap">
      <small>© 2026 ${label("company")}</small>
      <a class="text-link" href="${home}"><span>${label("home")}</span><span aria-hidden="true">↗</span></a>
    </div>
  </footer>
</body>
</html>
`;
}

const check = process.argv.includes("--check");
for (const solution of solutions) {
  for (const [index, language] of languages.entries()) {
    const file = join(root, pathFor(solution, language));
    const page = renderPage(solution, language, index);
    if (check) {
      const savedPage = (await readFile(file, "utf8")).replace(/\r\n/g, "\n");
      if (savedPage !== page) throw new Error("Outdated solution page: " + file);
    } else {
      await mkdir(dirname(file), { recursive: true });
      await writeFile(file, page, "utf8");
    }
  }
}
console.log((check ? "Verified " : "Built ") + solutions.length * languages.length + " solution pages.");
